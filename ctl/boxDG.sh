#!/bin/bash
# Box DG (a 24 GB card): why does SP make generation WORSE than the raw window alone (60 GRPO problems: raw 43-44, SP 35-38
# for every SP so far) while the teacher-forced KL says SP helps (on the model's own text too)? With the latest window-0
# all-layer state (spW0_window0.pt):
#  1. the 60 problems again (seed 2), SP at window 1024 and the raw window alone (1056), each storing the generated token ids
#     and every sampled token's log p under the generator's own logits (--roll-lp);
#  2. eval --dump on both runs' text, scored with SP and with the raw window: per token log p (student / full-KV teacher),
#     forward and reverse KL. The SP run scored with SP is the generation path vs the teacher-forced path, token by token
#     (a bug in either shows as sampled tokens the teacher-forced student finds nearly impossible); the teacher's log p of
#     the tokens each run actually sampled shows how often a run wanders where the full-KV model would not go.
# Results to archive/sp3/dg/, marker DONE_DG1.
# serial 2: on-policy distillation with the reverse KL (after DONE_DG1). Rounds of: 96 new prompts (ctl/gen_more.jsonl,
# shuffled: math / competition / MMLU-Pro / chat / code) generated by the current student under the deployment loop (SP +
# raw window 1024, cap 12288, Qwen3 sampling); then the student (pooler + all 28 layers, lr 1e-4 / 1e-5, constant) trained on
# those generations at the deployment state (chunk after a full window) to minimise KL(student || full-KV teacher) per
# token, the teacher = the original Qwen3 reading the whole generation. Every 3 rounds the 60 problems with SP (seeds 1
# and 2), every 6 also the raw window alone (damage gauge); spOP_latest.pt to the hub after each check. Runs until STOP_OP.
# serial 3: the on-policy loop is held (job2 stopped before it starts). The user: "ignoring SP" is always available, so a working
# setup can never end below the raw window - yet every SP did, GRPO included. First split content from slot: the 60
# problems (seed 2, as the serial-1 runs) with the SP of an EMPTY buffer (a fixed set of 32 vectors) and with ANOTHER
# problem's SP; plus the teacher-forced KL of the null SP on the SP run's text. Marker DONE_DG3.
# serial 4: serial 1's dump loop reused $t inside put() (its retry loop), so after the first upload the text name became "1" -
# the raw-window scorings (SP-run text and raw-run text scored with the raw window) never ran. They run after job3.
# serial 5: the null SP (a fixed set of 32 vectors, no content) scored 35/60 like the real SP (raw window 41): the slot itself
# costs the answers, not what the soft prompts say. Where it bites: (a) attention probe - per layer, how much attention the
# window's queries give the slot / the first prompt token / the window, and the hidden-state norms at the slot (real SP, null
# SP, 32 newlines, no slot); (b) the 60 problems (seed 2) with the raw window cut to 1024 (no slot - is it the 32 fewer
# window tokens?) and with 32 real newline tokens in the slot (soft vectors vs ordinary tokens); (c) the teacher-forced KL of
# both on the SP run's text. Marker DONE_DG5.
# serial 6: the diagnosis says the training objective is the problem - on the SP run's own text the slot (real or null)
# LOWERS the forward KL to the full-KV teacher (raw 0.1642, null 0.1617, SP 0.1591) but RAISES the reverse KL (raw 0.2175,
# null 0.2261, SP 0.2274), and sampling follows the reverse side: every training so far minimised the forward KL. The held
# on-policy reverse-KL loop (serial 2's job2) now starts after serial 5 (DONE_DG5).
# serial 7: a possible oversight in the loop itself - once the raw window passes the answer's opening "<think>\n" the tag is
# gone (raw window and SP alike): the model writes on mid-thought without the tag that says it is thinking, and the slot sits
# exactly where the tag belongs (which would explain why a content-free slot hurts as much as the real SP). The 60 problems
# (seed 2) with the tag kept after the prompt (--pin-think): raw window, SP, null SP. The on-policy loop is held again (it
# now waits for a GO_OP marker, set by a later serial with the layout these runs pick). Marker DONE_DG7.
# serial 8: the raw window cut to 1024 (no slot at all) scored 36/60 - like every SP run (35-38) - while the raw window of 1056
# scored 41-44: the "SP hurts" comparison was SP+1024 against a raw window 32 tokens longer, and the slot is attended ~0.5%
# (probe) - SP is simply ignored at window 1024. Is 32 raw tokens really worth ~6 problems, or is it an artefact of the
# window being a multiple of the chunk (1024 = 8 x 128)? Raw window 1088 (not a multiple) and 1152 (a multiple), seed 2;
# 1024 and 1056 again at seed 3; 1024 with the <think> tag kept. Marker DONE_DG8.
